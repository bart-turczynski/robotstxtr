# The invisible, space and separator class (ROBO-uphlyomt): writes
# R/invisible-class-ucd.R from the Unicode Character Database.
#
# The class is every code point that is General_Category Zs (other than
# U+0020), Zl, Zp or Cf (other than the prepended concatenation marks
# below), or Default_Ignorable_Code_Point, and the C1 controls U+0080 to
# U+009F. Zs, Zl and Zp are of kind "space"; the rest are of kind
# "invisible". An assigned point carries its UnicodeData name (a C1 control
# its Unicode 1.0 name, or "<control>" when it has none); an unassigned
# default-ignorable point carries none.
#
# Run from the package root with the folder that holds the two UCD files
# of the pinned version as the one argument:
#   Rscript data-raw/unicode-invisible-class.R <ucd-folder>
# The folder holds UnicodeData-17.0.0.txt and
# DerivedCoreProperties-17.0.0.txt, downloaded from
# https://www.unicode.org/Public/17.0.0/ucd/ and renamed. The script checks
# their SHA-256 below and stops on a mismatch; it reads no network. Never
# commit the UCD files. The output is ASCII and byte-identical across runs.

ucd_version <- "17.0.0"
ucd_files <- c(
  UnicodeData = "UnicodeData-17.0.0.txt",
  DerivedCoreProperties = "DerivedCoreProperties-17.0.0.txt"
)
ucd_sha256 <- c(
  UnicodeData =
    "2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c",
  DerivedCoreProperties =
    "24c7fed1195c482faaefd5c1e7eb821c5ee1fb6de07ecdbaa64b56a99da22c08"
)
output <- file.path("R", "invisible-class-ucd.R")

# The Cf points with the Prepended_Concatenation_Mark property (PropList.txt
# 17.0.0, Prepended_Concatenation_Mark): number signs and marks that show a
# glyph (ARABIC NUMBER SIGN, SYRIAC ABBREVIATION MARK, KAITHI NUMBER SIGN),
# so they are not invisible and stay out of the class. PropList.txt is not
# among the files read here, so the 13 points are written out; each is
# checked below to be Cf in UnicodeData.txt.
prepended_marks <- c(
  0x0600:0x0605, 0x06DD, 0x070F, 0x0890, 0x0891, 0x08E2, 0x110BD, 0x110CD
)

args <- commandArgs(trailingOnly = TRUE)
if (length(args) != 1L) {
  stop("usage: Rscript data-raw/unicode-invisible-class.R <ucd-folder>",
       call. = FALSE)
}
paths <- file.path(args[[1L]], ucd_files)
names(paths) <- names(ucd_files)
for (file in names(paths)) {
  if (!file.exists(paths[[file]])) {
    stop("missing ", paths[[file]], call. = FALSE)
  }
  found <- unname(tools::sha256sum(paths[[file]]))
  if (!identical(found, ucd_sha256[[file]])) {
    stop("SHA-256 mismatch for ", paths[[file]], ": ", found, call. = FALSE)
  }
}

# UnicodeData.txt: one line per assigned point, fields separated by `;`.
# A range written as a First/Last pair holds no point of the class (none is
# Cf, Zs, Zl, Zp or default-ignorable), so it is skipped.
data <- utils::read.table(paths[["UnicodeData"]], sep = ";", quote = "",
                          comment.char = "", colClasses = "character",
                          col.names = paste0("f", 0:14))
data <- data[!grepl(", (First|Last)>$", data$f1), ]
data_point <- strtoi(data$f0, 16L)
category <- data$f2
name <- data$f1
control <- category == "Cc"
name[control] <- ifelse(nzchar(data$f10[control]), data$f10[control],
                        "<control>")

# DerivedCoreProperties.txt: `XXXX(..YYYY)? ; Property # comment`.
lines <- readLines(paths[["DerivedCoreProperties"]], warn = FALSE)
lines <- sub("#.*$", "", lines)
lines <- lines[grepl("; Default_Ignorable_Code_Point *$", lines)]
ranges <- trimws(sub(";.*$", "", lines))
ignorable <- unlist(lapply(strsplit(ranges, "..", fixed = TRUE),
                           function(bounds) {
                             bounds <- strtoi(bounds, 16L)
                             bounds[[1L]]:bounds[[length(bounds)]]
                           }))

space <- data_point[category %in% c("Zs", "Zl", "Zp") & data_point != 0x20]
stopifnot(identical(category[match(prepended_marks, data_point)],
                    rep("Cf", length(prepended_marks))),
          !any(prepended_marks %in% ignorable))
invisible <- c(data_point[category == "Cf"], 0x80:0x9F, ignorable)
invisible <- setdiff(invisible, c(space, prepended_marks))
class <- sort(unique(c(space, invisible)))
assigned <- class[class %in% data_point]
unassigned <- setdiff(class, assigned)
stopifnot(!anyNA(class), all(unassigned %in% ignorable))

hex <- function(point) sprintf("%04X", point)
records <- sprintf("  \"%s|%s|%s\"", hex(assigned),
                   ifelse(assigned %in% space, "space", "invisible"),
                   name[match(assigned, data_point)])
stopifnot(!any(grepl("[\"\\\\]", name[match(assigned, data_point)])))

# Unassigned points as runs of consecutive code points.
run <- cumsum(c(1L, diff(unassigned) != 1L))
runs <- vapply(split(unassigned, run), function(points) {
  if (length(points) == 1L) {
    sprintf("0x%s", hex(points))
  } else {
    sprintf("0x%s:0x%s", hex(points[[1L]]), hex(points[[length(points)]]))
  }
}, character(1L))

out <- c(
  "# Generated by data-raw/unicode-invisible-class.R (ROBO-uphlyomt): do not",
  "# edit by hand; regenerate with the pinned UCD files instead.",
  sprintf("# Unicode %s: UnicodeData.txt SHA-256", ucd_version),
  sprintf("#   %s", ucd_sha256[["UnicodeData"]]),
  "# DerivedCoreProperties.txt SHA-256",
  sprintf("#   %s", ucd_sha256[["DerivedCoreProperties"]]),
  "#",
  "# The invisible, space and separator class: Zs other than U+0020, Zl, Zp,",
  "# Cf other than the 13 prepended concatenation marks (PropList.txt",
  "# 17.0.0, Prepended_Concatenation_Mark), Default_Ignorable_Code_Point",
  "# and the C1 controls. Each assigned point is one record",
  "# \"XXXX|kind|NAME\": kind \"space\" for Zs, Zl and Zp, \"invisible\" for",
  "# the rest; a C1 control's name is its Unicode 1.0 name, or \"<control>\"",
  "# when it has none.",
  sprintf("# %d assigned points, %d unassigned.", length(assigned),
          length(unassigned)),
  "validation_unicode_class_records <- c(",
  paste0(records, c(rep(",", length(records) - 1L), "")),
  ")",
  "",
  "# The unassigned default-ignorable points, kind \"invisible\", no name.",
  "validation_unicode_class_unassigned <- c(",
  paste0("  ", runs, c(rep(",", length(runs) - 1L), "")),
  ")"
)
stopifnot(!any(grepl("[^\\x01-\\x7F]", out, perl = TRUE)),
          all(nchar(out) <= 80L))
writeLines(out, output, useBytes = TRUE)
cat(sprintf("wrote %s: %d assigned, %d unassigned\n", output,
            length(assigned), length(unassigned)))
